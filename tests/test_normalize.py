# A poem keeps ای apart after a word (the vocative: پندم مده ای دوست); prose joins it.
def test_verse():
    assert profile("fa", "poem") == "verse" and profile("fa", "document") == "fa"
    run = lambda steps, text: [text := outside(step, text) for step in steps][-1]
    assert run(PROFILES["verse"], "پندم مده ای دوست") == "پندم مده ای دوست"
    assert run(PROFILES["fa"], "خانه ای خرید") == f"خانه{Z}ای خرید"
    assert run(PROFILES["verse"], "خانه ام") == f"خانه{Z}ام"
    assert normalize("پندم مده ای دوست", verse=True) == run(PROFILES["verse"], "پندم مده ای دوست")


